// ── Solvable Procedural Generator (100% Solvable Guaranteed) ──
export function generateRandomFlowPuzzle(size = 5, numColors = 5) {
  const colorIds = ['red', 'yellow', 'blue', 'green', 'orange', 'cyan', 'purple', 'magenta', 'lime', 'white'];
  const colorsToUse = colorIds.slice(0, Math.min(numColors, colorIds.length));
  
  let attempts = 0;
  while (attempts < 1000) {
    attempts++;
    const grid = Array(size).fill(null).map(() => Array(size).fill(null));
    const paths = [];
    const unvisited = new Set();
    for (let r = 0; r < size; r++) {
      for (let c = 0; c < size; c++) unvisited.add(r * size + c);
    }

    for (let cIdx = 0; cIdx < colorsToUse.length; cIdx++) {
      const color = colorsToUse[cIdx];
      if (unvisited.size === 0) break;

      const unvisArr = Array.from(unvisited).map(id => ({ r: Math.floor(id / size), c: id % size }));
      unvisArr.sort((a, b) => {
        const countA = [[0,1],[0,-1],[1,0],[-1,0]].filter(([dr, dc]) => unvisited.has((a.r+dr)*size + (a.c+dc))).length;
        const countB = [[0,1],[0,-1],[1,0],[-1,0]].filter(([dr, dc]) => unvisited.has((b.r+dr)*size + (b.c+dc))).length;
        return countA - countB;
      });

      const start = unvisArr[0];
      const path = [start];
      grid[start.r][start.c] = color;
      unvisited.delete(start.r * size + start.c);

      const targetLen = Math.max(3, Math.floor(unvisited.size / (colorsToUse.length - cIdx)));

      while (path.length < targetLen && unvisited.size > 0) {
        const head = path[path.length - 1];
        const deltas = [[0,1],[0,-1],[1,0],[-1,0]].sort(() => Math.random() - 0.5);
        let moved = false;
        for (const [dr, dc] of deltas) {
          const nr = head.r + dr;
          const nc = head.c + dc;
          if (nr >= 0 && nr < size && nc >= 0 && nc < size && unvisited.has(nr * size + nc)) {
            grid[nr][nc] = color;
            unvisited.delete(nr * size + nc);
            path.push({ r: nr, c: nc });
            moved = true;
            break;
          }
        }
        if (!moved) break;
      }

      if (path.length >= 2) paths.push({ color, path });
      else {
        grid[start.r][start.c] = null;
        unvisited.add(start.r * size + start.c);
      }
    }

    if (unvisited.size > 0) {
      let stuck = false;
      while (unvisited.size > 0 && !stuck) {
        stuck = true;
        for (const p of paths) {
          const head = p.path[p.path.length - 1];
          for (const [dr, dc] of [[0,1],[0,-1],[1,0],[-1,0]]) {
            const nr = head.r + dr;
            const nc = head.c + dc;
            if (nr >= 0 && nr < size && nc >= 0 && nc < size && unvisited.has(nr * size + nc)) {
              grid[nr][nc] = p.color;
              unvisited.delete(nr * size + nc);
              p.path.push({ r: nr, c: nc });
              stuck = false;
              break;
            }
          }
          if (unvisited.size === 0) break;
        }
      }
    }

    if (unvisited.size === 0 && paths.length >= 3) {
      return {
        id: Date.now(),
        size,
        pairs: paths.map(p => ({ color: p.color, p1: p.path[0], p2: p.path[p.path.length - 1] })),
        solution: paths
      };
    }
  }

  return LEVEL_PACKS[0].levels[0];
}

// ── Backtracking Flow Solver (for Hints) ──
export function solveFlowPuzzle(size, pairs) {
  const grid = Array(size).fill(null).map(() => Array(size).fill(null));
  const colorEndpoints = {};
  pairs.forEach((p) => {
    grid[p.p1.r][p.p1.c] = p.color;
    grid[p.p2.r][p.p2.c] = p.color;
    colorEndpoints[p.color] = [p.p1, p.p2];
  });

  const solutionPaths = {};
  const colorsList = pairs.map((p) => p.color);

  function getNeighbors(r, c) {
    const res = [];
    const deltas = [[0, 1], [0, -1], [1, 0], [-1, 0]];
    for (const [dr, dc] of deltas) {
      const nr = r + dr;
      const nc = c + dc;
      if (nr >= 0 && nr < size && nc >= 0 && nc < size) {
        res.push({ r: nr, c: nc });
      }
    }
    return res;
  }

  function backtrack(colorIdx, currentPath) {
    if (colorIdx === colorsList.length) {
      let filled = 0;
      for (let r = 0; r < size; r++) {
        for (let c = 0; c < size; c++) {
          if (grid[r][c] !== null) filled++;
        }
      }
      return filled === size * size;
    }

    const color = colorsList[colorIdx];
    const [start, end] = colorEndpoints[color];

    if (!currentPath || currentPath.length === 0) {
      currentPath = [start];
    }

    const currentHead = currentPath[currentPath.length - 1];

    if (currentHead.r === end.r && currentHead.c === end.c) {
      solutionPaths[color] = [...currentPath];
      const nextSuccess = backtrack(colorIdx + 1, []);
      if (nextSuccess) return true;
      delete solutionPaths[color];
      return false;
    }

    const neighbors = getNeighbors(currentHead.r, currentHead.c);
    neighbors.sort((a, b) => {
      const distA = Math.abs(a.r - end.r) + Math.abs(a.c - end.c);
      const distB = Math.abs(b.r - end.r) + Math.abs(b.c - end.c);
      return distA - distB;
    });

    for (const n of neighbors) {
      const isEnd = n.r === end.r && n.c === end.c;
      const isEmpty = grid[n.r][n.c] === null;

      if (isEnd || isEmpty) {
        const prevVal = grid[n.r][n.c];
        grid[n.r][n.c] = color;
        currentPath.push(n);

        if (backtrack(colorIdx, currentPath)) return true;

        currentPath.pop();
        grid[n.r][n.c] = prevVal;
      }
    }
    return false;
  }

  const solved = backtrack(0, []);
  if (solved) {
    return Object.keys(solutionPaths).map((color) => ({
      color,
      path: solutionPaths[color]
    }));
  }
  return null;
}

// ── Progress Storage Helpers ──
const FLOW_STORAGE_KEY = 'gamehub_flow_progress';

export function getFlowProgress() {
  try {
    const raw = localStorage.getItem(FLOW_STORAGE_KEY);
    if (!raw) return {};
    return JSON.parse(raw);
  } catch {
    return {};
  }
}

export function saveFlowLevelProgress(packId, levelId, { stars, moves, time }) {
  try {
    const data = getFlowProgress();
    const packKey = packId + '_' + levelId;
    const existing = data[packKey] || { stars: 0, moves: Infinity, time: Infinity };

    data[packKey] = {
      completed: true,
      stars: Math.max(existing.stars || 0, stars || 1),
      moves: Math.min(existing.moves || Infinity, moves),
      time: Math.min(existing.time || Infinity, time),
      timestamp: new Date().toISOString()
    };

    localStorage.setItem(FLOW_STORAGE_KEY, JSON.stringify(data));
    return data;
  } catch {
    return {};
  }
}
